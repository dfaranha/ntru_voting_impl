/**
 * @file
 *
 * The voter's proof that a ballot is well formed (include/ntru_ballot.h), on
 * LaZer's linear proofs. The statement, over R_q of degree 2048 and the NTRU
 * prime q, with witness w = (s, e, u, m):
 *
 *   c = 2 h s + 2 e + m
 *   0 = m - u
 *
 * with ||(s, e)|| <= B, ||u|| <= 1 and m binary (lazer/ntru_ballot.py). A
 * binary m equal to a u of norm at most 1 has at most one coefficient 1, so m
 * is X^j or 0: one vote, or none. Which j is a valid candidate is left to the
 * tally, as for any ciphertext.
 *
 * LaZer lifts the statement to its own ring of degree 64 and an 84-bit proof
 * modulus; the parameters, generated by its lin-codegen.sage, are in
 * lazer/ntru_ballot.h.
 */

#include <stdlib.h>
#include <string.h>

#include "lazer.h"
#include "../lazer/ntru_ballot.h"
#include "ntru_ballot.h"

#define N 		NTRU_BALLOT_DEG
#define Q 		NTRU_BALLOT_Q
#define ROWS 	2
#define COLS 	4
#define PARAMS 	ntru_ballot

/* floor(B^2) for the bound on ||(s, e)||, B = 1.2 sqrt(2048) as in
 * lazer/ntru_ballot.py. */
#define L2_SE 	2949

static const uint8_t ppseed[32] = "ntru_voting_impl ballot, LaZer";

static int64_t centre(int64_t x) {
	x %= Q;
	if (x > Q / 2) {
		x -= Q;
	} else if (x < -(Q / 2)) {
		x += Q;
	}
	return x;
}

/* The statement as LaZer reads it, A w + t = 0: A row-major, each
 * polynomial's coefficients in turn, then t, all centred mod q. */
typedef struct {
	int64_t *A, *t;
} stmt_t;

static void stmt_init(stmt_t *st, const int64_t c[], const int64_t h[]) {
	st->A = calloc((size_t) ROWS * COLS * N, sizeof(int64_t));
	st->t = calloc((size_t) ROWS * N, sizeof(int64_t));
	/* row 0: (2h, 2, 0, 1) . (s, e, u, m) - c = 0 */
	for (int i = 0; i < N; i++) {
		st->A[(0 * COLS + 0) * N + i] = centre(2 * h[i]);
		st->t[0 * N + i] = centre(-c[i]);
	}
	st->A[(0 * COLS + 1) * N] = 2;
	st->A[(0 * COLS + 3) * N] = 1;
	/* row 1: (0, 0, -1, 1) . (s, e, u, m) = 0 */
	st->A[(1 * COLS + 2) * N] = -1;
	st->A[(1 * COLS + 3) * N] = 1;
}

static void stmt_clear(stmt_t *st) {
	free(st->A);
	free(st->t);
}

/* Whether c = 2 h s + 2 e + m in R_q. LaZer's prover does not check its
 * statement, and on a false one its responses leave the range the encoding is
 * sized for and overrun the proof buffer. */
static int equation_holds(const int64_t c[], const int64_t h[],
		const int64_t s[], const int64_t e[], const int64_t m[]) {
	__int128 *acc = calloc(N, sizeof(__int128));
	int ok = 1;

	/* 2 h s in Z[X]/(X^N + 1), s ternary */
	for (int i = 0; i < N; i++) {
		if (s[i] == 0) {
			continue;
		}
		for (int j = 0; j < N; j++) {
			__int128 x = (__int128) 2 * h[j] * s[i];
			if (i + j < N) {
				acc[i + j] += x;
			} else {
				acc[i + j - N] -= x;
			}
		}
	}
	for (int i = 0; i < N && ok; i++) {
		__int128 d = acc[i] + 2 * e[i] + m[i] - c[i];
		ok = d % Q == 0;
	}
	free(acc);
	return ok;
}

/* Whether (s, e, m) is a witness of the form the proof needs: s and e ternary
 * with ||(s, e)||^2 <= L2_SE, m binary with at most one coefficient set. */
static int witness_ok(const int64_t s[], const int64_t e[], const int64_t m[]) {
	int64_t l2 = 0, ones = 0;

	for (int i = 0; i < N; i++) {
		if (s[i] < -1 || s[i] > 1 || e[i] < -1 || e[i] > 1
				|| m[i] < 0 || m[i] > 1) {
			return 0;
		}
		l2 += s[i] * s[i] + e[i] * e[i];
		ones += m[i];
	}
	return l2 <= L2_SE && ones <= 1;
}

void ntru_ballot_setup(void) {
	lazer_init();
}

size_t ntru_ballot_proof_len(void) {
	return lin_params_get_prooflen(PARAMS);
}

int ntru_ballot_prove(uint8_t *proof, size_t *len, const int64_t c[],
		const int64_t h[], const int64_t s[], const int64_t e[],
		const int64_t m[], const uint8_t *ctx, size_t ctxlen) {
	lin_prover_state_t P;
	polymat_t A;
	polyvec_t t, w;
	stmt_t st;
	int64_t *wv;
	INT_T(q, 1);

	if (!witness_ok(s, e, m) || !equation_holds(c, h, s, e, m)) {
		return 0;
	}
	int_set_i64(q, Q);
	POLYRING_T(Rq, q, N);
	stmt_init(&st, c, h);
	wv = malloc((size_t) COLS * N * sizeof(int64_t));
	memcpy(wv + 0 * N, s, N * sizeof(int64_t));
	memcpy(wv + 1 * N, e, N * sizeof(int64_t));
	memcpy(wv + 2 * N, m, N * sizeof(int64_t));	/* u = m */
	memcpy(wv + 3 * N, m, N * sizeof(int64_t));
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	polyvec_alloc(w, Rq, COLS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);
	polyvec_set_coeffvec_i64(w, wv);

	*len = ntru_ballot_proof_len();
	lin_prover_init(P, ppseed, PARAMS);
	lin_prover_set_statement(P, A, t);
	lin_prover_set_witness(P, w);
	lin_prover_prove_ctx(P, proof, len, NULL, ctx, ctxlen);
	lin_prover_clear(P);

	polymat_free(A);
	polyvec_free(t);
	polyvec_free(w);
	free(wv);
	stmt_clear(&st);
	return 1;
}

int ntru_ballot_verify(const uint8_t *proof, size_t len, const int64_t c[],
		const int64_t h[], const uint8_t *ctx, size_t ctxlen) {
	lin_verifier_state_t V;
	polymat_t A;
	polyvec_t t;
	stmt_t st;
	size_t used = len;
	int ok;
	INT_T(q, 1);

	/* The encoding's length varies; ntru_ballot_proof_len() bounds it. */
	if (len == 0 || len > ntru_ballot_proof_len()) {
		return 0;
	}
	int_set_i64(q, Q);
	POLYRING_T(Rq, q, N);
	stmt_init(&st, c, h);
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);

	lin_verifier_init(V, ppseed, PARAMS);
	lin_verifier_set_statement(V, A, t);
	ok = lin_verifier_verify_ctx(V, proof, &used, ctx, ctxlen) && used == len;
	lin_verifier_clear(V);

	polymat_free(A);
	polyvec_free(t);
	stmt_clear(&st);
	return ok;
}
