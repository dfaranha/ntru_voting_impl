/**
 * @file
 *
 * The voter's proof that a ballot is well formed (include/ntru_ballot.h), on
 * LaZer's linear proofs, stated over LaZer's own ring R_64 = Z_q[Y]/(Y^64 + 1).
 *
 * R_q of degree N = 2048 is R_64[X]/(X^K - Y) with K = N / 64 = 32: an
 * element a is sum_r X^r a_r(Y), its piece a_r holding the coefficients
 * a[r + K l]. A vote for candidate j is X^(K j) = Y^j, which lives in piece 0
 * alone, so the vote and the elements about it are single elements of R_64
 * rather than K of them each, as lifting the statement from R_q would make
 * them. With witness w = (s_0..s_31, e_0..e_31, u, m, m'):
 *
 *   c_r = (2 h s)_r + 2 e_r + [r = 0] m		for r < K
 *   0   = m - u
 *   0   = Y^(64 - ncand) m - m'
 *
 * with ||(s, e)|| <= B, ||u|| <= 1 and m, m' binary (lazer/ntru_ballot.py).
 * The first K rows are c = 2 h s + 2 e + m in R_q, piece by piece, with the
 * vote's other pieces zero because they are not in the witness. A binary m
 * equal to a u of norm at most 1 is Y^j or 0: one vote, or none. The last row
 * makes j a candidate: R_64 is negacyclic, so Y^(64 - ncand) Y^j is
 * Y^(64 - ncand + j), binary, for j < ncand, and -Y^(j - ncand), which is not,
 * for j >= ncand. A blank ballot, m = 0, is allowed.
 *
 * Lifting c = 2 h s + 2 e + m with m and m' full elements of R_q made them 32
 * binary elements of R_64 each; this way the binary part is 2 elements, not
 * 64, and the witness 67, not 160. The parameters, generated by LaZer's
 * lin-codegen.sage for an 83-bit proof modulus, are in lazer/ntru_ballot.h.
 */

#include <stdlib.h>
#include <string.h>

#include "lazer.h"
#include "../lazer/ntru_ballot.h"
#include "ntru_ballot.h"

#define N 		NTRU_BALLOT_DEG
#define Q 		NTRU_BALLOT_Q
#define D 		64					/* LaZer's ring degree */
#define K 		NTRU_BALLOT_STRIDE	/* N / D: pieces of an element of R_q */
#define ROWS 	(K + 2)
#define COLS 	(2 * K + 3)
#define COL_U 	(2 * K)
#define COL_M 	(2 * K + 1)
#define COL_M2 	(2 * K + 2)
#define PARAMS 	ntru_ballot

/* floor(B^2) for the bound on ||(s, e)||, B = 1.2 sqrt(2048) as in
 * lazer/ntru_ballot.py. */
#define L2_SE 	2949

static const uint8_t ppseed[32] = "ntru_voting_impl ballot, LaZer";

static int64_t centre(int64_t x) {
	x %= Q;
	if (x > Q / 2) {
		x -= Q;
	} else if (x < -(Q / 2)) {
		x += Q;
	}
	return x;
}

/* The statement as LaZer reads it, A w + t = 0 over R_64: A row-major, each
 * polynomial's D coefficients in turn, then t, all centred mod q. */
typedef struct {
	int64_t *A, *t;
} stmt_t;

/* Coefficient l of piece r of an element of R_q. */
#define PIECE(a, r, l) 	((a)[(r) + K * (l)])

static void stmt_init(stmt_t *st, const int64_t c[], const int64_t h[],
		int ncand) {
	st->A = calloc((size_t) ROWS * COLS * D, sizeof(int64_t));
	st->t = calloc((size_t) ROWS * D, sizeof(int64_t));
	/* rows r < K: sum_t (2 h)_{r,t} s_t + 2 e_r + [r = 0] m - c_r = 0, where
	 * multiplication by 2 h is the K x K matrix whose entry (r, t) is 2 h_(r-t)
	 * for t <= r and 2 Y h_(r-t+K) for t > r: X^(i+t) is X^r Y when i + t
	 * wraps past K. */
	for (int r = 0; r < K; r++) {
		for (int t = 0; t < K; t++) {
			int64_t *a = st->A + ((size_t) r * COLS + t) * D;

			if (t <= r) {
				for (int l = 0; l < D; l++) {
					a[l] = centre(2 * PIECE(h, r - t, l));
				}
			} else {
				/* Y p: coefficient l is p's l - 1, and the top one wraps
				 * negated to the bottom */
				a[0] = centre(-2 * PIECE(h, r - t + K, D - 1));
				for (int l = 1; l < D; l++) {
					a[l] = centre(2 * PIECE(h, r - t + K, l - 1));
				}
			}
		}
		st->A[((size_t) r * COLS + K + r) * D] = 2;
		for (int l = 0; l < D; l++) {
			st->t[r * D + l] = centre(-PIECE(c, r, l));
		}
	}
	st->A[((size_t) 0 * COLS + COL_M) * D] = 1;
	/* row K: m - u = 0 */
	st->A[((size_t) K * COLS + COL_U) * D] = -1;
	st->A[((size_t) K * COLS + COL_M) * D] = 1;
	/* row K + 1: Y^(D - ncand) m - m' = 0 */
	st->A[((size_t) (K + 1) * COLS + COL_M) * D + D - ncand] = 1;
	st->A[((size_t) (K + 1) * COLS + COL_M2) * D] = -1;
}

static void stmt_clear(stmt_t *st) {
	free(st->A);
	free(st->t);
}

/* Whether c = 2 h s + 2 e + m in R_q. LaZer's prover does not check its
 * statement, and on a false one its responses leave the range the encoding is
 * sized for and overrun the proof buffer. */
static int equation_holds(const int64_t c[], const int64_t h[],
		const int64_t s[], const int64_t e[], const int64_t m[]) {
	__int128 *acc = calloc(N, sizeof(__int128));
	int ok = 1;

	/* 2 h s in Z[X]/(X^N + 1), s ternary */
	for (int i = 0; i < N; i++) {
		if (s[i] == 0) {
			continue;
		}
		for (int j = 0; j < N; j++) {
			__int128 x = (__int128) 2 * h[j] * s[i];
			if (i + j < N) {
				acc[i + j] += x;
			} else {
				acc[i + j - N] -= x;
			}
		}
	}
	for (int i = 0; i < N && ok; i++) {
		__int128 d = acc[i] + 2 * e[i] + m[i] - c[i];
		ok = d % Q == 0;
	}
	free(acc);
	return ok;
}

/* Whether (s, e, m) is a witness of the form the proof needs: s and e ternary
 * with ||(s, e)||^2 <= L2_SE, m binary with at most one coefficient set, and
 * that one X^(K j) for a candidate j < ncand. */
static int witness_ok(const int64_t s[], const int64_t e[], const int64_t m[],
		int ncand) {
	int64_t l2 = 0, ones = 0;

	for (int i = 0; i < N; i++) {
		if (s[i] < -1 || s[i] > 1 || e[i] < -1 || e[i] > 1
				|| m[i] < 0 || m[i] > 1) {
			return 0;
		}
		l2 += s[i] * s[i] + e[i] * e[i];
		ones += m[i];
		if (m[i] != 0 && (i % K != 0 || i / K >= ncand)) {
			return 0;
		}
	}
	return l2 <= L2_SE && ones <= 1;
}

void ntru_ballot_setup(void) {
	lazer_init();
}

size_t ntru_ballot_proof_len(void) {
	return lin_params_get_prooflen(PARAMS);
}

int ntru_ballot_prove(uint8_t *proof, size_t *len, const int64_t c[],
		const int64_t h[], const int64_t s[], const int64_t e[],
		const int64_t m[], int ncand, const uint8_t *ctx, size_t ctxlen) {
	lin_prover_state_t P;
	polymat_t A;
	polyvec_t t, w;
	stmt_t st;
	int64_t *wv;
	INT_T(q, 1);

	if (ncand < 1 || ncand > NTRU_BALLOT_MAXCAND || !witness_ok(s, e, m, ncand)
			|| !equation_holds(c, h, s, e, m)) {
		return 0;
	}
	int_set_i64(q, Q);
	POLYRING_T(Rq, q, D);
	stmt_init(&st, c, h, ncand);
	wv = calloc((size_t) COLS * D, sizeof(int64_t));
	for (int r = 0; r < K; r++) {
		for (int l = 0; l < D; l++) {
			wv[r * D + l] = PIECE(s, r, l);
			wv[(K + r) * D + l] = PIECE(e, r, l);
		}
	}
	for (int l = 0; l < D; l++) {
		wv[COL_U * D + l] = PIECE(m, 0, l);		/* u = m */
		wv[COL_M * D + l] = PIECE(m, 0, l);
	}
	for (int j = 0; j < ncand; j++) {			/* m' = Y^(D - ncand) m */
		wv[COL_M2 * D + D - ncand + j] = PIECE(m, 0, j);
	}
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	polyvec_alloc(w, Rq, COLS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);
	polyvec_set_coeffvec_i64(w, wv);

	*len = ntru_ballot_proof_len();
	lin_prover_init(P, ppseed, PARAMS);
	lin_prover_set_statement(P, A, t);
	lin_prover_set_witness(P, w);
	lin_prover_prove_ctx(P, proof, len, NULL, ctx, ctxlen);
	lin_prover_clear(P);

	polymat_free(A);
	polyvec_free(t);
	polyvec_free(w);
	free(wv);
	stmt_clear(&st);
	return 1;
}

int ntru_ballot_verify(const uint8_t *proof, size_t len, const int64_t c[],
		const int64_t h[], int ncand, const uint8_t *ctx, size_t ctxlen) {
	lin_verifier_state_t V;
	polymat_t A;
	polyvec_t t;
	stmt_t st;
	size_t used = len;
	int ok;
	INT_T(q, 1);

	/* The encoding's length varies; ntru_ballot_proof_len() bounds it. */
	if (len == 0 || len > ntru_ballot_proof_len() || ncand < 1
			|| ncand > NTRU_BALLOT_MAXCAND) {
		return 0;
	}
	int_set_i64(q, Q);
	POLYRING_T(Rq, q, D);
	stmt_init(&st, c, h, ncand);
	polymat_alloc(A, Rq, ROWS, COLS);
	polyvec_alloc(t, Rq, ROWS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);

	lin_verifier_init(V, ppseed, PARAMS);
	lin_verifier_set_statement(V, A, t);
	ok = lin_verifier_verify_ctx(V, proof, &used, ctx, ctxlen) && used == len;
	lin_verifier_clear(V);

	polymat_free(A);
	polyvec_free(t);
	stmt_clear(&st);
	return ok;
}
